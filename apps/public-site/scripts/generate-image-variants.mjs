#!/usr/bin/env node
// Pre-generates every responsive width for the site's static images, so that
// Vercel never has to optimize an image on demand.
//
// WHY
// Vercel's Image Optimization is billed per (source, width, quality) cache
// MISS or STALE, and Hobby includes 5,000 transformations per month. This
// site emits 8 widths per photo, and with minimumCacheTTL at 31 days every
// one of them is re-billed roughly monthly — measured at ~2,800/month at 20
// projects and rising ~105 per new project. When that allowance runs out,
// Vercel returns 402 for any variant it has not already cached and the
// browser shows the alt text instead of the photo. That is exactly the
// outage this site already had.
//
// Generating the widths at build time removes the meter entirely: the
// browser requests a plain static file that already exists, so there is
// nothing to transform, nothing to bill, and no ceiling on how many
// projects the site can carry.
//
// HOW THE IMAGES ARE RESIZED — no cropping, no distortion
// Only a WIDTH is given to sharp. The height is left undefined, so sharp
// derives it from the source aspect ratio: the whole photo is scaled down,
// never cropped, never stretched. `withoutEnlargement` stops a small source
// being blown up into a blurry larger file.
//
// A file is written for EVERY width in DEVICE_WIDTHS even when the source is
// narrower than that width. The bytes are then simply the source's own size
// (capped by withoutEnlargement), but the file exists. That matters because
// the custom loader (../image-loader.js) runs in the browser and cannot check
// whether a file exists — it must be able to compute a URL that is always
// valid.
//
// Output goes to public/_img/ and is NOT committed: it is a build artifact,
// regenerated by `prebuild` on every deploy. Committing ~1,900 binaries would
// permanently bloat the repository for every clone.
//
// WHY THE ENCODED FILES ARE CACHED IN .next/cache
// Encoding is by far the most expensive thing this build does. Measured on
// the real Vercel build machine (2 cores, 8 GB) for deployment 36c4b15:
//
//   17:02:26  generation starts
//   17:36:38  generation ends      <- 34m 12s
//   17:39:19  deployment complete  <- 37m 33s total
//
// against a hard 45-minute cap on the Build Step, after which Vercel
// interrupts the build and the deployment FAILS. That left about seven
// minutes of headroom, while the photo set grows by roughly 17 images with
// every project added -- so the site was a handful of projects away from
// being unable to deploy at all.
//
// Almost all of that work was repeated: the sources had not changed, only
// the code had. Vercel restores `.next/cache` between builds of the same
// project, so encoded variants are kept there and hard-linked into
// public/_img instead of being re-encoded. An unchanged photo is then
// linked in microseconds rather than re-encoded in seconds.
//
// Correctness rests on the cache key, not on a filename: it is the SHA-1 of
// the source file's BYTES plus the encoder settings. Replace a photo while
// keeping its path and the hash changes, so it is re-encoded; change
// AVIF_QUALITY or the width list and every entry is re-encoded. A stale
// variant therefore cannot be served, which a path-and-mtime key could not
// guarantee (git does not preserve mtimes across a clone).
//
// Entries not used by a run are deleted, so the cache tracks the current
// photo set instead of growing forever. Vercel caps the build cache at 1 GB;
// if it is ever exceeded or evicted the cache is simply absent on the next
// build, which costs a slow build, never a wrong one.

import { mkdir, readdir, readFile, writeFile, access, link, unlink, copyFile, stat, rm } from 'node:fs/promises';
import { dirname, join, relative, resolve, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import os from 'node:os';
import sharp from 'sharp';

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(here, '..');
const PUBLIC_DIR = join(appRoot, 'public');
const OUT_DIR = join(PUBLIC_DIR, '_img');

// Vercel restores `.next/cache` between builds of the same project; nothing
// else in the workspace survives. Overridable so a different CI can point it
// at whatever directory that CI persists.
const CACHE_DIR =
  process.env.IMAGE_VARIANT_CACHE_DIR || join(appRoot, '.next', 'cache', 'image-variants');

// Must stay in step with `images.deviceSizes` in next.config.js. The loader
// is only ever handed one of these values by next/image.
const DEVICE_WIDTHS = [640, 750, 828, 1080, 1200, 1536, 1920, 2048];
// next/image also uses imageSizes for small, fixed-size images (icons,
// avatars, logos) when a `sizes` prop is present.
const IMAGE_WIDTHS = [16, 32, 48, 64, 96, 128, 256, 384];
const ALL_WIDTHS = [...new Set([...IMAGE_WIDTHS, ...DEVICE_WIDTHS])].sort((a, b) => a - b);

// Chosen by measurement against what production serves today, not by feel.
// Mean absolute error vs the losslessly-downscaled source, at w=2048 on a
// 4240x2384 project photo:
//   Vercel q=100 (live today)  0.81   60KB
//   AVIF q=62                  0.78   53KB   already better, and smaller
//   AVIF q=72                  0.67   72KB   <- chosen
//   AVIF q=80                  0.57   96KB
// q=72 is ~17% closer to the original than the site currently serves, for
// ~20% more bytes. Since transformations are no longer metered, the only
// cost of higher quality is transfer, and architectural photography is the
// whole point of this site.
const AVIF_QUALITY = 72;

// libavif's search effort. Measured on two real 4240x2384 project photos,
// encoding all 16 widths each:
//   effort 4  ->  8507 ms/image,  2711 KB/image
//   effort 2  ->  2308 ms/image,  2693 KB/image
// 3.7x faster for very slightly SMALLER output -- the extra search simply
// does not pay off on photographic content at this quality. That speed
// matters: this runs inside a Vercel build capped at 45 minutes, on machines
// with far fewer cores than a developer laptop.
const AVIF_EFFORT = 2;

const SOURCE_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp']);

// Directories under public/ that are never rendered through next/image.
const SKIP_DIRS = new Set(['_img', 'documents', 'email_icons']);

const exists = (p) => access(p).then(() => true, () => false);

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (dir === PUBLIC_DIR && SKIP_DIRS.has(entry.name)) continue;
      yield* walk(full);
    } else if (SOURCE_EXT.has(extname(entry.name).toLowerCase())) {
      yield full;
    }
  }
}

/**
 * Output path for one (source, width) pair.
 *
 * The full relative source path is preserved and the width plus a new
 * extension appended, so two files with the same basename in different
 * folders can never collide. ../image-loader.js recomputes this exact
 * string in the browser and the two MUST stay in step.
 */
function variantPath(relSource, width) {
  return join(OUT_DIR, `${relSource}.${width}.avif`);
}

// Everything that changes the BYTES this script writes. It namespaces the
// cache, so editing quality/effort/widths invalidates every entry at once
// rather than silently serving files encoded under the old settings.
const ENCODER_SIG = `avif-q${AVIF_QUALITY}-e${AVIF_EFFORT}-w${ALL_WIDTHS.join('_')}`;
const SIG_DIR = join(CACHE_DIR, createHash('sha1').update(ENCODER_SIG).digest('hex').slice(0, 12));

/** Cache location for one (source content, width) pair. */
const cachePath = (sourceHash, width) => join(SIG_DIR, sourceHash, `${width}.avif`);

/**
 * Put the cached file at `out`.
 *
 * A hard link, not a copy: same inode, so the 385 MB of variants is stored
 * once on disk no matter that it appears in two places, and linking costs
 * no I/O. Vercel collects public/ by reading files, and a hard link IS the
 * file, so the deployment output is byte-identical either way.
 *
 * copyFile is the fallback for filesystems that refuse the link (a cache on
 * a different device, or Windows without the privilege) -- correct, just
 * slower.
 */
async function placeFromCache(cached, out) {
  await mkdir(dirname(out), { recursive: true });
  try {
    await link(cached, out);
  } catch (error) {
    if (error.code === 'EEXIST') {
      await unlink(out);
      return placeFromCache(cached, out);
    }
    if (error.code === 'EXDEV' || error.code === 'EPERM' || error.code === 'ENOSYS') {
      await copyFile(cached, out);
      return;
    }
    throw error;
  }
}

// Encode several images at once. sharp does its work on libuv's threadpool
// and releases the event loop, so this is close to linear in cores. It
// matters: generating ~5,800 variants serially took ~20 minutes locally, and
// this runs inside a Vercel build that is capped at 45 minutes.
const CONCURRENCY = Math.max(2, (os.availableParallelism?.() ?? os.cpus().length) - 1);

const force = process.argv.includes('--force');
let generated = 0;
let fromCache = 0;
let sources = 0;
let failed = 0;
const failures = [];
// Cache entries this run depends on. Anything else under SIG_DIR belongs to a
// photo that has since been replaced or deleted, and is pruned at the end.
const liveHashes = new Set();

console.log('Generating responsive image variants (aspect ratio preserved, no cropping)...');

async function processOne(file) {
  const relSource = relative(PUBLIC_DIR, file);

  // Read once: the bytes are both the cache key and sharp's input, so this
  // replaces the separate metadata() open the previous version did.
  let input;
  try {
    input = await readFile(file);
  } catch (error) {
    failed += 1;
    failures.push(`${relSource}: unreadable (${error.message})`);
    return;
  }

  const sourceHash = createHash('sha1').update(input).digest('hex').slice(0, 20);
  liveHashes.add(sourceHash);
  sources += 1;

  // Split the widths into those already encoded under this exact source
  // content and those that still have to be produced.
  const todo = [];
  for (const width of ALL_WIDTHS) {
    const out = variantPath(relSource, width);
    const cached = cachePath(sourceHash, width);
    if (!force && (await exists(cached))) {
      try {
        await placeFromCache(cached, out);
        fromCache += 1;
        continue;
      } catch (error) {
        // A cache entry that cannot be placed is treated as absent rather
        // than fatal: re-encoding is always available as the correct answer.
        failures.push(`${relSource} @${width}: cache unusable (${error.message}), re-encoding`);
      }
    }
    todo.push({ width, out, cached });
  }
  if (todo.length === 0) return;

  // Decode the source ONCE and clone the decoded pipeline per width.
  // Calling sharp(file) inside the loop re-read and re-decoded the original
  // for every width -- 16 full JPEG decodes per photo, on sources up to 8MB.
  // That dominated the runtime, and this build has to finish inside Vercel's
  // 45-minute cap on machines with far fewer cores than a laptop.
  let base;
  try {
    base = sharp(input, { failOn: 'none' }).rotate();
    const meta = await base.metadata();
    if (!meta.width || !meta.height) {
      failed += 1;
      failures.push(`${relSource}: no dimensions`);
      return;
    }
    await base.stats(); // force the decode once, up front
  } catch (error) {
    failed += 1;
    failures.push(`${relSource}: decode failed (${error.message})`);
    return;
  }

  for (const { width, out, cached } of todo) {
    try {
      const buf = await base
        .clone()
        .resize({
          width,
          // height intentionally omitted -> sharp derives it from the source
          // aspect ratio. The complete image is scaled; nothing is cropped
          // and nothing is stretched.
          withoutEnlargement: true,
          fit: 'inside',
        })
        .avif({ quality: AVIF_QUALITY, effort: AVIF_EFFORT })
        .toBuffer();

      // Write into the cache first, then link out of it, so public/_img and
      // the cache can never disagree about what a given file contains.
      await mkdir(dirname(cached), { recursive: true });
      await writeFile(cached, buf);
      await placeFromCache(cached, out);
      generated += 1;
    } catch (error) {
      failed += 1;
      failures.push(`${relSource} @${width}: ${error.message}`);
    }
  }
}

/**
 * Drop cache entries for source content no longer present, and any directory
 * left by a previous encoder signature. Without this the cache only ever
 * grows -- every replaced photo would leave its old variants behind until it
 * pushed the cache past Vercel's 1 GB ceiling.
 */
async function pruneCache() {
  let removed = 0;
  let entries;
  try {
    entries = await readdir(CACHE_DIR, { withFileTypes: true });
  } catch {
    return 0; // no cache yet
  }
  for (const sig of entries) {
    if (!sig.isDirectory()) continue;
    const sigPath = join(CACHE_DIR, sig.name);
    if (sigPath !== SIG_DIR) {
      await rm(sigPath, { recursive: true, force: true });
      removed += 1;
      continue;
    }
    for (const entry of await readdir(sigPath, { withFileTypes: true })) {
      if (!entry.isDirectory() || liveHashes.has(entry.name)) continue;
      await rm(join(sigPath, entry.name), { recursive: true, force: true });
      removed += 1;
    }
  }
  return removed;
}

/** Total bytes under a directory, for the 1 GB build-cache ceiling warning. */
async function dirSize(dir) {
  let total = 0;
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return 0;
  }
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) total += await dirSize(full);
    else total += (await stat(full)).size;
  }
  return total;
}

const startedAt = Date.now();
const cacheWasPresent = await exists(SIG_DIR);

const queue = [];
for await (const file of walk(PUBLIC_DIR)) queue.push(file);
console.log(`  ${queue.length} source images, ${CONCURRENCY} at a time`);
console.log(
  `  cache: ${relative(appRoot, CACHE_DIR)} ` +
    `(${cacheWasPresent ? 'restored' : 'EMPTY - every variant will be encoded'})`
);

let cursor = 0;
await Promise.all(
  Array.from({ length: CONCURRENCY }, async () => {
    while (cursor < queue.length) {
      await processOne(queue[cursor++]);
    }
  })
);

const pruned = await pruneCache();
const cacheBytes = await dirSize(CACHE_DIR);
const cacheMB = Math.round(cacheBytes / 1e6);
const elapsed = ((Date.now() - startedAt) / 1000).toFixed(1);

console.log(
  `\n  source images : ${sources}` +
    `\n  encoded now   : ${generated}` +
    `\n  from cache    : ${fromCache}` +
    `\n  pruned        : ${pruned}` +
    `\n  failed        : ${failed}` +
    `\n  cache size    : ${cacheMB} MB` +
    `\n  elapsed       : ${elapsed}s`
);

// Vercel caps a build cache at 1 GB and silently drops it when exceeded,
// which would turn every future build back into a full re-encode. Warn while
// there is still room to act (raise AVIF_QUALITY's efficiency, trim widths,
// or move the cache elsewhere) rather than after builds start timing out.
if (cacheBytes > 700e6) {
  console.warn(
    `\n  WARNING: the variant cache is ${cacheMB} MB. Vercel's build cache limit` +
      `\n  is 1 GB TOTAL, shared with Next.js's own cache (~260 MB here). If the` +
      `\n  limit is passed the cache is dropped and every build re-encodes from` +
      `\n  scratch -- roughly 34 minutes against a 45-minute build cap.`
  );
}

if (failures.length) {
  console.error('\nFailures:');
  for (const f of failures.slice(0, 20)) console.error(`  ${f}`);
  if (failures.length > 20) console.error(`  ...and ${failures.length - 20} more`);
  // A source that cannot be processed would fall back to being served
  // unoptimized rather than breaking the page, so this is a warning, not a
  // build failure. It is still surfaced loudly.
  console.error('\nThese sources will be served without a pre-generated variant.');
}

console.log('\nDone. These are static files: Vercel performs zero image transformations for them.');
